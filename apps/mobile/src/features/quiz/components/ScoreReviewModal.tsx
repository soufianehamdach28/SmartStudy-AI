import React from 'react';
import {
  Modal,
  ScrollView,
  StyleSheet,
  Text,
  TouchableOpacity,
  View,
} from 'react-native';
import { SafeAreaView } from 'react-native-safe-area-context';
import type { QuizAttemptResponse, QuizQuestion } from '@smartstudy/shared';

interface ScoreReviewModalProps {
  visible: boolean;
  attempt: QuizAttemptResponse | null;
  questions: QuizQuestion[];
  onClose: () => void;
  onRetry: () => void;
}

const OPTION_LETTERS = ['A', 'B', 'C', 'D'];

export function ScoreReviewModal({
  visible,
  attempt,
  questions,
  onClose,
  onRetry,
}: ScoreReviewModalProps) {
  if (!attempt) return null;

  const isPassed = attempt.score >= 70;
  const questionMap = new Map<string, QuizQuestion>();
  for (const q of questions) {
    questionMap.set(q.id, q);
  }

  return (
    <Modal
      visible={visible}
      animationType="slide"
      presentationStyle="pageSheet"
      onRequestClose={onClose}
    >
      <SafeAreaView style={styles.safeArea}>
        {/* Header */}
        <View style={styles.header}>
          <Text style={styles.headerTitle}>Quiz Results</Text>
          <TouchableOpacity
            onPress={onClose}
            accessibilityRole="button"
            accessibilityLabel="Close review"
            style={styles.closeButton}
          >
            <Text style={styles.closeButtonText}>Done</Text>
          </TouchableOpacity>
        </View>

        <ScrollView
          style={styles.scroll}
          contentContainerStyle={styles.scrollContent}
          showsVerticalScrollIndicator={false}
        >
          {/* Score Card */}
          <View
            style={[
              styles.scoreCard,
              isPassed ? styles.scoreCardPassed : styles.scoreCardFailed,
            ]}
            testID="score-card"
          >
            <Text style={styles.scoreEmoji}>{isPassed ? '🏆' : '📚'}</Text>
            <Text
              style={[
                styles.scorePercentage,
                isPassed ? styles.scoreTextPassed : styles.scoreTextFailed,
              ]}
            >
              {Math.round(attempt.score)}%
            </Text>
            <Text style={styles.scoreFraction}>
              {attempt.correctCount} of {attempt.totalQuestions} questions correct
            </Text>
            <Text style={styles.scoreMessage}>
              {isPassed
                ? 'Great job! You demonstrated solid comprehension.'
                : 'Keep practicing! Review the explanations below to master the topic.'}
            </Text>
          </View>

          {/* AI Disclaimer */}
          <View style={styles.disclaimerBanner}>
            <Text style={styles.disclaimerText}>
              ⚠️ <Text style={styles.disclaimerBold}>AI Disclaimer:</Text> Explanations are generated by AI. Refer to your original course document for definitive facts.
            </Text>
          </View>

          {/* Question Breakdown */}
          <Text style={styles.sectionTitle}>Question Breakdown</Text>
          {attempt.answers.map((ans, index) => {
            const question = questionMap.get(ans.questionId);
            const userChoiceText = question?.options[ans.selectedIndex] ?? 'No answer';
            const correctChoiceText = question?.options[ans.correctIndex] ?? '';

            return (
              <View
                key={ans.questionId}
                style={[
                  styles.reviewItem,
                  ans.isCorrect ? styles.reviewItemCorrect : styles.reviewItemIncorrect,
                ]}
                testID={`review-item-${index}`}
              >
                <View style={styles.reviewItemHeader}>
                  <Text style={styles.questionIndex}>Question {index + 1}</Text>
                  <View
                    style={[
                      styles.resultBadge,
                      ans.isCorrect ? styles.badgeCorrect : styles.badgeIncorrect,
                    ]}
                  >
                    <Text
                      style={[
                        styles.resultBadgeText,
                        ans.isCorrect
                          ? styles.badgeTextCorrect
                          : styles.badgeTextIncorrect,
                      ]}
                    >
                      {ans.isCorrect ? '✓ Correct' : '✗ Incorrect'}
                    </Text>
                  </View>
                </View>

                {question && (
                  <Text style={styles.questionPrompt}>{question.prompt}</Text>
                )}

                {/* Selected Choice */}
                <View style={styles.choiceRow}>
                  <Text style={styles.choiceLabel}>Your answer:</Text>
                  <Text
                    style={[
                      styles.choiceValue,
                      ans.isCorrect ? styles.choiceCorrect : styles.choiceIncorrect,
                    ]}
                  >
                    ({OPTION_LETTERS[ans.selectedIndex]}) {userChoiceText}
                  </Text>
                </View>

                {/* Correct Choice if user was wrong */}
                {!ans.isCorrect && (
                  <View style={styles.choiceRow}>
                    <Text style={styles.choiceLabel}>Correct answer:</Text>
                    <Text style={[styles.choiceValue, styles.choiceCorrect]}>
                      ({OPTION_LETTERS[ans.correctIndex]}) {correctChoiceText}
                    </Text>
                  </View>
                )}

                {/* Explanation */}
                <View style={styles.explanationBox}>
                  <Text style={styles.explanationTitle}>Explanation:</Text>
                  <Text style={styles.explanationText}>{ans.explanation}</Text>
                </View>
              </View>
            );
          })}

          {/* Action Buttons */}
          <View style={styles.actionRow}>
            <TouchableOpacity
              style={styles.retryButton}
              onPress={onRetry}
              accessibilityRole="button"
              accessibilityLabel="Try quiz again"
            >
              <Text style={styles.retryButtonText}>🔄 Try Quiz Again</Text>
            </TouchableOpacity>
          </View>
        </ScrollView>
      </SafeAreaView>
    </Modal>
  );
}

